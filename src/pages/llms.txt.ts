import type { APIRoute } from 'astro';
import { SITE } from '@/data/site';
import { liveGames } from '@/data/games.registry';
import { LAYOUTS } from '@/engines/mahjong/layouts';

export const GET: APIRoute = ({ site }) => {
  const base = site?.toString() ?? 'https://example.com/';
  const lines = [
    `# ${SITE.name}`,
    '',
    `> ${SITE.description}`,
    '',
    '## Games',
    ...liveGames().map((g) => `- [${g.name}](${new URL(g.path, base)}): ${g.tagline}`),
    '',
    '## Mahjong layouts',
    ...Object.entries(LAYOUTS).map(
      ([slug, m]) => `- [${m.layout.name}](${new URL(`/mahjong/${slug}/`, base)}): ${m.layout.slots.length} tiles, ${m.difficulty}. ${m.blurb}`,
    ),
    '',
    '## Facts',
    '- Every deal is generated by reverse play and is therefore solvable.',
    '- Boards keep tiles at a minimum 44px touch target and rotate on portrait phones.',
    '- Keyboard navigation, screen-reader announcements, large-tile and high-contrast modes are built in.',
  ];
  return new Response(lines.join('\n'), { headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
};
